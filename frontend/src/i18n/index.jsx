const DICTS = { en, hi, mr }

const I18nContext = createContext(null)

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try {
      return window.__kcLang || window.localStorage.getItem('kcLang') || 'en'
    } catch {
      return 'en'
    }
  })
  const t = useCallback((key) => DICTS[lang]?.[key] ?? DICTS.en[key] ?? key, [lang])
  const tMaterial = useCallback(
    (cat) => MATERIAL_NAMES[LEGACY_CATEGORY_ALIASES[cat] ?? cat]?.[lang] ?? cat,
    [lang]
  )
  const tStatus = useCallback(
    (s) => STATUS_LABELS[s]?.[lang] ?? STATUS_LABELS[s]?.en ?? s.replaceAll('_', ' '),
    [lang]
  )
  const change = useCallback((code) => {
    window.__kcLang = code
    try {
      window.localStorage.setItem('kcLang', code)
    } catch {}
    setLang(code)
  }, [])
  const value = useMemo(
    () => ({ lang, setLang: change, t, tMaterial, tStatus, speech: LANGUAGES.find((l) => l.code === lang)?.speech ?? 'en-IN' }),
    [lang, t, tMaterial, tStatus, change]
  )
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider')
  return ctx
}
